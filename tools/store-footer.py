def fmt_dist(m, lang):
    if m < 1000:
        return '%d m' % m
    d = (int(m) + 50) // 100          # integer rounding, half up: 1950 m -> 2,0 km (float '%.1f' gave 1,9)
    km = '%d.%d' % (d // 10, d % 10)
    return (km.replace('.', ',') if lang == 'vi' else km) + ' km'

