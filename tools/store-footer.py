# One reusable, original SVG map pin, declared once per page as a <symbol> and drawn with <use>.
# Brand colours only: a single Brass body (#8A6A3B) with a Paper hole (#F4F2ED), no gradient,
# no pure black or white. No image file, no external request.
PIN_SYMBOL = ('<svg class="nb-defs" aria-hidden="true" focusable="false">'
  '<symbol id="nb-pin" viewBox="0 0 24 28">'
  '<path d="M12 1.2C7.1 1.2 3.3 5 3.3 9.8c0 6.2 7.1 13.6 7.9 14.4.4.4 1.2.4 1.6 0 .8-.8 7.9-8.2 7.9-14.4C20.7 5 16.9 1.2 12 1.2Z" fill="#8A6A3B"/>'
  '<circle cx="12" cy="9.6" r="3.4" fill="#F4F2ED"/>'
  '</symbol></svg>')


def pin(cls='nb-pin'):
    return '<svg class="%s" aria-hidden="true" focusable="false"><use href="#nb-pin"/></svg>' % cls

def render_nearby(c, lang):
    ext = 'target="_blank" rel="noopener noreferrer"'
    intro = html.escape(c['nb_intro'], quote=False)
    for phrase in c['nb_strong']:
        intro = intro.replace(phrase, '<strong>%s</strong>' % phrase, 1)
    items = []
    # shown nearest first (walking distance, then walking time), the same order on both pages
    for a in sorted(NEARBY, key=lambda a: (a['m'], a['mins'])):
        name = html.escape(a[lang], quote=False); aname = html.escape(a[lang])
        items.append(dict(
            place='<a class="nb-place" href="%s" %s aria-label="%s">%s<span class="nb-name">%s</span></a>' % (
                html.escape(a['place']), ext, c['nb_place_aria'] % aname, pin(), name),
            walk='<a class="nb-walk" href="%s" %s aria-label="%s">%s</a>' % (
                walk_url(a['dest']), ext, c['nb_walk_aria'] % aname, c['nb_walk']),
            dist=fmt_dist(a['m'], lang), mins=c['nb_walkmins'] % a['mins']))
    lis = '\n'.join(
        '        <li class="nb-item">%s<p class="nb-meta"><span class="nb-dist">%s</span><span class="nb-sep" aria-hidden="true"> · </span><span class="nb-mins">%s</span></p>%s</li>'
        % (i['place'], i['dist'], i['mins'], i['walk']) for i in items)
    return f'''    <section class="nearby" data-track-scope="nearby-attractions" aria-labelledby="nearby-title">
      {PIN_SYMBOL}
      <div class="nb-head">
        <h2 id="nearby-title" class="nb-title">{pin('nb-pin nb-pin--title')}{c['nb_title']}</h2>
        <p class="nb-intro">{intro}</p>
      </div>
      <ul class="nb-list" aria-label="{c['nb_caption']}">
{lis}
      </ul>
      <p class="nb-note">{c['nb_note']}</p>
    </section>'''

